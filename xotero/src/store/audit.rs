use sqlx::{Postgres, Transaction};

use crate::domain::UserId;

pub(super) enum BootstrapAction {
    Identity,
    InstanceAdmin,
}

impl BootstrapAction {
    fn as_str(&self) -> &'static str {
        match self {
            Self::Identity => "bootstrap.identity",
            Self::InstanceAdmin => "bootstrap.instance-admin",
        }
    }
}

pub(super) enum AuditOutcome {
    Success,
    Noop,
    Denied,
}

#[derive(Clone, Copy)]
pub enum WebSessionAction {
    Login,
    Logout,
}

pub(super) async fn append_web(
    tx: &mut Transaction<'_, Postgres>,
    action: WebSessionAction,
    user: Option<i64>,
) -> sqlx::Result<()> {
    let action = match action {
        WebSessionAction::Login => "web.login",
        WebSessionAction::Logout => "web.logout",
    };
    let outcome = match user {
        Some(_) => AuditOutcome::Success,
        None => AuditOutcome::Denied,
    };
    append_event(tx, user, user, action, outcome).await
}

/// Append within the caller's mutation transaction. Correlation is generated by
/// PostgreSQL for this non-HTTP startup operation, never copied from claims.
pub(super) async fn append(
    tx: &mut Transaction<'_, Postgres>,
    subject: UserId,
    action: &BootstrapAction,
    outcome: AuditOutcome,
) -> sqlx::Result<()> {
    append_event(tx, None, Some(subject.get()), action.as_str(), outcome).await
}

async fn append_event(
    tx: &mut Transaction<'_, Postgres>,
    actor: Option<i64>,
    subject: Option<i64>,
    action: &str,
    outcome: AuditOutcome,
) -> sqlx::Result<()> {
    let outcome = match outcome {
        AuditOutcome::Success => "success",
        AuditOutcome::Noop => "noop",
        AuditOutcome::Denied => "denied",
    };
    sqlx::query(
        "select xotero_append_audit($1,$2,$3::audit_action,$4::audit_outcome,gen_random_uuid())",
    )
    .bind(actor)
    .bind(subject)
    .bind(action)
    .bind(outcome)
    .execute(&mut **tx)
    .await?;
    Ok(())
}
